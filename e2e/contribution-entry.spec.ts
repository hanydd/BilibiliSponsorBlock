import { expect, test } from "./fixtures/extension";
import { readLocalStorage, writeLocalStorage } from "./support/extensionStorage";

test("contribution discovery dot supports hover, keyboard and permanent dismissal", async ({extensionPage: page, extensionId, extensionServiceWorker: worker, extensionContext: context}) => {
    await writeLocalStorage(worker,{contributionCalendarNewDismissed:false});
    await page.setViewportSize({width:400,height:650});
    await page.goto(`chrome-extension://${extensionId}/popup.html`);
    const entry=page.getByRole("button",{name:"我的贡献",exact:true});
    const dot=page.locator(".sbContributionNew");
    const dismiss=page.getByRole("button",{name:"不再显示我的贡献的新功能提示"});
    await expect(dot).toBeVisible();
    await expect(page.locator(".sbYourWorkBox .ant-spin-spinning")).toHaveCount(0);
    await expect(entry).toHaveCSS("color", "rgb(0, 161, 214)");
    const before=await entry.boundingBox();
    await entry.hover();
    await expect(page.getByText("查看提交记录和收获",{exact:true})).toBeVisible();
    await dismiss.click();
    await expect(dot).toHaveCount(0);
    await expect.poll(()=>readLocalStorage(worker,"contributionCalendarNewDismissed")).toBe(true);
    await expect(entry).not.toHaveAttribute("data-new", "true");
    const after=await entry.boundingBox();
    expect({width:after.width,height:after.height,x:after.x}).toEqual({width:before.width,height:before.height,x:before.x});
    await page.reload();
    await expect(entry).toBeVisible();
    await expect(dot).toHaveCount(0);

    await writeLocalStorage(worker,{contributionCalendarNewDismissed:false});
    await page.reload();
    await entry.focus();
    await expect(dismiss).toBeVisible();
    await page.keyboard.press("Tab");
    await expect(dismiss).toBeFocused();
    await page.keyboard.press("Shift+Tab");
    await expect(entry).toBeFocused();
    await page.keyboard.press("Tab");
    await expect(dismiss).toBeFocused();
    await page.keyboard.press("Tab");
    const next = page.locator("#sbFooter").locator("a[href], button:enabled").filter({visible:true}).first();
    await expect(next).toBeFocused();
    await expect(dismiss).not.toBeVisible();
    await page.keyboard.press("Shift+Tab");
    await expect(entry).toBeFocused();
    await page.keyboard.press("Tab");
    await expect(dismiss).toBeFocused();
    await page.keyboard.press("Escape");
    await expect(entry).toBeFocused();
    await expect(dismiss).not.toBeVisible();
    const opened=context.waitForEvent("page");
    await page.keyboard.press("Enter");
    const dashboard=await opened;
    await dashboard.waitForURL("**/contributions/index.html");
    await expect(dot).toHaveCount(0);
    await expect.poll(()=>readLocalStorage(worker,"contributionCalendarNewDismissed")).toBe(true);
    await dashboard.close();
    await page.reload();
    await expect(dot).toHaveCount(0);
    await expect(entry).toBeVisible();
});

test("options and contributions link to each other in the same tab", async ({ extensionPage: page, extensionId }) => {
    const base = `chrome-extension://${extensionId}`;
    await page.setViewportSize({ width: 390, height: 760 });
    await page.goto(`${base}/options/options.html`);
    const entry = page.locator("#createdBy nav a[href='../contributions/index.html']");
    await expect(entry).toHaveText(/我的贡献|我的貢獻/);
    await entry.click();
    await expect(page).toHaveURL(`${base}/contributions/index.html`);
    const nav = page.getByRole("navigation", { name: "页面导航" });
    const website = nav.getByRole("link", { name: "官网" });
    await expect(website).toBeInViewport();
    await expect(website).toHaveAttribute("href", "https://bsbsb.top/");
    await expect(website).toHaveAttribute("target", "_blank");
    await nav.getByRole("link", { name: "设置" }).click();
    await expect(page).toHaveURL(`${base}/options/options.html`);
    await expect(page.locator("#behavior")).toBeVisible();
});
